import { chromium } from '@playwright/test';
import { createApp } from '../server/index.js';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

const {server}=createApp({dbPath:':memory:'});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL || 'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByLabel('Full name').fill('Hospital Admin');
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password',{exact:true}).fill('Browser-test-password!');
  await page.getByRole('button',{name:'Create administrator account'}).click();
  await page.getByRole('heading',{name:'Welcome, Hospital.'}).waitFor();
  const session=await page.evaluate(async()=>fetch('/api/me').then(r=>r.json()));
  for(const role of ['reception','doctor','nurse','laboratory','pharmacy','billing']) {
    const status=await page.evaluate(async({role,csrf})=>{
      const response=await fetch('/api/users',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':csrf},body:JSON.stringify({name:`Staff ${role}`,email:`${role}@example.test`,password:'Browser-test-password!',role})});return response.status;
    },{role,csrf:session.csrf});assert.equal(status,201);
  }
  await page.getByRole('button',{name:'Locations & wards',exact:true}).click();
  await page.getByRole('button',{name:'Add location',exact:true}).click();
  await page.getByLabel('Facility code').fill('NAI');
  await page.getByLabel('Location name').fill('Nairobi Hospital');
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('button',{name:'Add ward',exact:true}).click();
  await page.getByLabel('Ward name').fill('Medical');
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('button',{name:'Add bed',exact:true}).click();
  await page.getByLabel('Ward',{exact:true}).selectOption({label:'Medical'});
  await page.getByLabel('Bed label').fill('M01');
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('button',{name:'Assign staff',exact:true}).click();
  await page.getByLabel('Staff member',{exact:true}).selectOption({label:'Staff doctor (Doctor)'});
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('Staff doctor',{exact:true}).waitFor();
  async function login(role) {
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email address').fill(`${role}@example.test`);
    await page.getByLabel('Password',{exact:true}).fill('Browser-test-password!');
    await page.getByRole('button',{name:/^Sign in/}).click();
    await page.getByRole('heading',{name:'Welcome, Staff.'}).waitFor();
  }
  await login('reception');
  await page.getByRole('button',{name:'Patient directory',exact:true}).click();
  await page.getByRole('button',{name:'Register patient'}).click();
  await page.getByLabel('First name').fill('Alex');
  await page.getByLabel('Last name').fill('Example');
  await page.getByLabel('Date of birth').fill('1990-05-14');
  await page.getByLabel('Sex',{exact:true}).selectOption('female');
  await page.getByRole('dialog').getByRole('button',{name:'Register patient'}).click();
  await page.getByRole('heading',{name:'Alex Example'}).waitFor();
  await login('doctor');
  await page.getByRole('button',{name:'Clinical workspace',exact:true}).click();
  await page.getByRole('button',{name:'Open encounter'}).click();
  await page.getByLabel('Find patient by name or medical record number').fill('Alex');
  await page.locator('#patient-options option').nth(1).waitFor({state:'attached'});
  await page.getByLabel('Patient',{exact:true}).selectOption({index:1});
  await page.getByLabel('Doctor',{exact:true}).selectOption({label:'Staff doctor'});
  await page.getByLabel('Reason for visit').fill('Synthetic browser workflow');
  await page.getByRole('dialog').getByRole('button',{name:'Open encounter'}).click();
  await page.getByRole('button',{name:'View record'}).click();
  await page.getByRole('button',{name:'Add note'}).click();
  await page.getByLabel('Note type').selectOption('clinical');
  await page.getByLabel('Care note',{exact:true}).fill('Synthetic assessment. Allergy history reviewed.');
  await page.getByRole('button',{name:'Save note'}).click();
  await page.getByText('Synthetic assessment. Allergy history reviewed.').waitFor();
  await page.getByRole('button',{name:'Place order'}).click();
  await page.getByLabel('Department',{exact:true}).selectOption('laboratory');
  await page.getByLabel('Test or medicine').fill('Synthetic laboratory test');
  await page.getByLabel('Clinical instructions').fill('Synthetic specimen and reporting instructions.');
  await page.getByRole('dialog').getByRole('button',{name:'Place order'}).click();
  await page.getByText('Synthetic laboratory test',{exact:true}).waitFor();
  await login('laboratory');
  await page.getByRole('button',{name:'Laboratory',exact:true}).click();
  await page.getByRole('button',{name:'Review'}).click();
  await page.getByLabel('Result, units, reference range, and comments').fill('Synthetic result confirmed.');
  await page.getByRole('button',{name:'Complete order'}).click();
  await page.getByText('completed',{exact:true}).waitFor();
  await login('doctor');
  await page.getByRole('button',{name:'Clinical workspace',exact:true}).click();
  await page.getByRole('button',{name:'View record'}).click();
  await page.getByText('Synthetic result confirmed.',{exact:true}).waitFor();
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/clinical-workspace.png',fullPage:true});
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await page.getByRole('heading',{name:'Welcome, Staff.'}).waitFor();
  await page.screenshot({path:'artifacts/overview.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/mobile-overview.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth),true,'Mobile layout must not overflow horizontally');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Inpatient ward',exact:true}).click();
  await page.getByRole('button',{name:'Admit patient',exact:true}).click();
  await page.getByLabel('Find patient by name or medical record number').fill('Alex');
  await page.locator('#patient-options option').nth(1).waitFor({state:'attached'});
  await page.getByLabel('Patient',{exact:true}).selectOption({index:1});
  await page.getByLabel('Admitting doctor',{exact:true}).selectOption({label:'Staff doctor'});
  await page.getByLabel('Bed',{exact:true}).selectOption({label:'Medical / M01'});
  await page.getByLabel('Reason for admission').fill('Synthetic inpatient care');
  await page.getByRole('dialog').getByRole('button',{name:'Admit patient',exact:true}).click();
  await page.getByText('admitted',{exact:true}).waitFor();
  await page.screenshot({path:'artifacts/inpatient-ward.png',fullPage:true});
  await page.getByRole('button',{name:'Discharge',exact:true}).click();
  await page.getByLabel('Discharge summary',{exact:true}).fill('Synthetic discharge and follow-up instructions.');
  await page.getByRole('dialog').getByRole('button',{name:'Discharge',exact:true}).click();
  await page.getByText('discharged',{exact:true}).waitFor();
  assert.deepEqual(errors,[],'No browser JavaScript errors');
  console.log('Browser workflow passed: setup, role login, registration, encounter, note, laboratory handoff, result visibility, and mobile layout.');
} finally {
  if(browser)await browser.close();
  server.closeAllConnections();await new Promise(resolve=>server.close(resolve));
}
